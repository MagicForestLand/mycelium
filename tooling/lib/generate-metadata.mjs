import {collectionCopy,collectionDescription,categoryCopy} from '../../collection/source/editorial.js';
import {traits,layerKeys,renderLayerKeys,layerNames,editions,beadPalette} from '../../collection/source/art.js';
import {assertProjectURL,jsonStringContent} from './generated-text.mjs';

// The collection avatar and banner share one canonical friend to avoid duplicating
// a second full SVG in on-chain metadata. Grouping paths saves bytecode.
export const collectionGenotype=[3,0,1,0,0,30];
export function collectionArtwork() {
  // Use the same glossy bead primitive as the NFT renderer, but define patterns
  // only for palette colors actually used by this one collection friend.
  const usedColors=new Set();

  const shapes=renderLayerKeys.map(key=>{
    const traitIndex=collectionGenotype[layerKeys.indexOf(key)];
    const paths=new Map(),bytes=Buffer.from(traits[key][traitIndex].data,'hex');

    for(let i=0;i<bytes.length;i+=4){
      const[x,y,n,c]=bytes.subarray(i,i+4);
      usedColors.add(c);
      paths.set(c,(paths.get(c)||'')+`M${x*5} ${y*5}h${n*5}v5h-${n*5}z`);
    }

    return [...paths]
      .map(([color,d])=>`<path fill="url(#brand-p${color})" d="${d}"/>`)
      .join('');
  }).join('');

  const defs=
    '<defs>'+
    '<radialGradient id="brand-shine" cx="30%" cy="24%" r="78%">'+
    '<stop stop-color="#fff" stop-opacity=".58"/>'+
    '<stop offset=".22" stop-color="#fff" stop-opacity=".12"/>'+
    '<stop offset=".45" stop-color="#000" stop-opacity="0"/>'+
    '<stop offset="1" stop-color="#000" stop-opacity=".8"/>'+
    '</radialGradient>'+
    '<g id="brand-bead">'+
    '<circle cx="2.5" cy="2.5" r="2.3"/>'+
    '<circle cx="2.5" cy="2.5" r="2.3" fill="url(#brand-shine)"/>'+
    '</g>'+
    [...usedColors]
      .sort((a,b)=>a-b)
      .map(color=>`<pattern id="brand-p${color}" width="5" height="5" patternUnits="userSpaceOnUse"><use href="#brand-bead" fill="${beadPalette[color]}"/></pattern>`)
      .join('')+
    '</defs>';

  return '<svg xmlns="http://www.w3.org/2000/svg" width="400" height="400" viewBox="0 0 400 400">'+
    defs+
    '<path fill="#101b17" d="M0 0h400v400H0z"/>'+
    shapes+
    '</svg>';
}
export const bannerOpen='<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="600" viewBox="0 0 1600 600"><path fill="#101b17" d="M0 0h1600v600H0z"/><g fill="#f3ead5" font-family="Georgia,serif"><text x="100" y="270" font-size="92">Mycelium Friends</text></g><text x="104" y="338" fill="#b3c49a" font-family="sans-serif" font-size="28" letter-spacing="2">by Magic Forest</text><g transform="translate(990 40) scale(1.3)">';
export const bannerClose='</g></svg>';
export function collectionMetadata() {
  const art=collectionArtwork();
  return {name:collectionCopy.name,description:collectionDescription,
    image:'data:image/svg+xml;base64,'+Buffer.from(art).toString('base64'),
    banner_image:'data:image/svg+xml;base64,'+Buffer.from(bannerOpen+art+bannerClose).toString('base64'),
    external_link:collectionCopy.projectURL};
}

const markdownCell=value=>String(value).replaceAll('|','\\|').replaceAll('\n',' ');
export function collectionCopyMarkdown() {
  const exampleGenotype=editions[0].genotype;
  const familySections=layerKeys.map(key=>{
    const rows=traits[key].map(trait=>`| ${markdownCell(trait.name)} | ${markdownCell(trait.description)} |`).join('\n');
    return `### ${layerNames[key]}\n\n${categoryCopy[key]}\n\n| Name | Field note |\n| --- | --- |\n${rows}`;
  }).join('\n\n');
  const compositions=editions.map(item=>`### ${item.name}\n\n${item.description}`).join('\n\n');
  const exampleTraits=layerKeys.map((key,index)=>{
    const trait=traits[key][exampleGenotype[index]];
    return `${layerNames[key]} - ${trait.name}: ${trait.description}`;
  }).join('\n\n');
  return `# ${collectionCopy.name} - collection copy

Generated from \`collection/source/editorial.js\` and the approved catalog exposed by \`collection/source/art.js\`. Do not edit this file by hand.

## Short description

${collectionCopy.shortDescription}

## Marketplace collection description

${collectionDescription}

## Meet a Mycelium Friend

${collectionCopy.friendIntroduction}

${collectionCopy.artwork}

## From the mushroom to the forest

${collectionCopy.tagline}

${collectionCopy.introduction}

${collectionCopy.ecology}

${collectionCopy.mission}

${collectionCopy.donors}

${collectionCopy.future}

${collectionCopy.closing}

## Where to go next

[Mycelium Friends](${collectionCopy.projectURL}) · [Project transparency](${collectionCopy.transparencyURL})

## The six families

${familySections}

## Curated compositions

These are gallery examples of selectable combinations, not extra NFT traits, rarity tiers, or separately guaranteed editions. The on-chain name remains Mycelium Friend #TOKEN_ID.

${compositions}

## Example NFT description

${collectionCopy.name.replace(/s$/,'')} #1

${collectionCopy.tokenDescription}

${exampleTraits}

## Publishing notes

- Standard token fields: name, description, external_url, embedded SVG image, six attributes. Individual field notes live in the description because custom trait descriptions are not a standard marketplace display field.
- Collection fields: name, description, embedded SVG avatar and banner, external_link, exposed through contractURI.
- The original artwork and all published metadata are on-chain. Project links are informational.
- This is copy prepared for deployment, not a claim that a public collection has already been deployed.
- No token grants land ownership, promises financial return, fixes a number of planted trees, or claims an existing venue or delivery date.
- Keep progress, claim instructions, allocations, dates and changing project information on the project website.
- Marketplace caching, presentation, creator attribution and manual profile fields still need checking after deployment. PNG avatar/banner exports are supplied for platforms with manual image-upload requirements.
`;
}
export function generateMetadataContent(copy=collectionCopy, description=collectionDescription) {
  const constants={TOKEN_DESCRIPTION:jsonStringContent(copy.tokenDescription,'TOKEN_DESCRIPTION'),PROJECT_URL:assertProjectURL(copy.projectURL),
    COLLECTION_PREFIX:'{"name":"'+jsonStringContent(copy.name,'collection name')+'","description":"'+jsonStringContent(description,'collection description')+'","image":"data:image/svg+xml;base64,',
    IMAGE_SVG:collectionArtwork(),BANNER_OPEN:bannerOpen,BANNER_CLOSE:bannerClose};
  for(const value of Object.values(constants))if(!/^[\x20-\x7e]*$/.test(value))throw Error('On-chain editorial constants must be printable ASCII');
  return '// SPDX-License-Identifier: MIT\n// Generated by npm run build from collection/source/editorial.js and the birth artwork.\npragma solidity ^0.8.24;\nlibrary MetadataContent {\n'+Object.entries(constants).map(([key,value])=>'    string internal constant '+key+' = '+JSON.stringify(value)+';\n').join('')+'}\n';
}
