// Preserve IArtBank and bead encoding. Large catalogs are split into fixed pages
// so every deployed runtime remains below Ethereum's contract-size limit.
import {assertJSONSafeASCII} from './generated-text.mjs';
export function generateBanks(traits, layerKeys) {
  const expected=['stem','cap','temperament','glasses','accessory','hobby'];
  if(JSON.stringify(layerKeys)!==JSON.stringify(expected))throw new Error('Invalid DNA layer order');
  for(const key of layerKeys){
    const items=traits[key];
    if(!items?.length||items.length>256)throw new Error(`${key}: require 1..256 birth traits`);
    if(new Set(items.map(t=>t.id)).size!==items.length)throw new Error(`${key}: duplicate trait ID`);
    for(const item of items){
      if(!/^[a-z0-9-]+$/.test(item.id)||!/^[\x20-\x21\x23-\x25\x27-\x3b\x3d\x3f-\x5b\x5d-\x7e]*$/.test(item.name))throw new Error(`${key}: unsafe trait ID or publication label`);
      if(!/^(?:[a-f0-9]{8})*$/.test(item.data))throw new Error(`${key}/${item.id}: invalid bead encoding`);
      if(typeof item.description!=='string'||!item.description.length||item.description.length>240||!/^[\x20-\x21\x23-\x25\x27-\x3b\x3d\x3f-\x5b\x5d-\x7e]+$/.test(item.description))throw new Error(`${key}/${item.id}: unsafe or missing description`);
    }
  }
  const header='// SPDX-License-Identifier: MIT\n// Generated by npm run build.\npragma solidity ^0.8.24;\nimport "../IArtBank.sol";\nimport "../BeadCodec.sol";\n';
  let source=header;
  const manifest=[];
  function leaf(name,items){
    let code=`\ncontract ${name} is IArtBank {\n    function count() external pure returns (uint256) { return ${items.length}; }\n    function part(uint8 index) external pure returns (string memory) { return BeadCodec.render(encodedPart(index)); }\n    function encodedPart(uint8 index) public pure returns (bytes memory) {\n`;
    items.forEach((t,i)=>code+=`        if (index == ${i}) return hex"${t.data}";\n`);
    code+='        revert InvalidTrait();\n    }\n    function label(uint8 index) external pure returns (string memory) {\n';
    items.forEach((t,i)=>code+=`        if (index == ${i}) return ${JSON.stringify(t.name)};\n`);
    code+='        revert InvalidTrait();\n    }\n    function description(uint8 index) external pure returns (string memory) {\n';
    items.forEach((t,i)=>code+=`        if (index == ${i}) return ${JSON.stringify(t.description)};\n`);
    return code+'        revert InvalidTrait();\n    }\n}\n';
  }
  for(const key of layerKeys){
    const name=key[0].toUpperCase()+key.slice(1)+'Bank',items=traits[key];
    const chunks=[];let chunk=[],cost=0;
    for(const item of items){
      // Budget the additional story selector and bytes; compiled size gates remain authoritative.
      const size=item.data.length/2+250+item.name.length+item.description.length;
      if(chunk.length&&cost+size>22000){chunks.push(chunk);chunk=[];cost=0;}
      chunk.push(item);cost+=size;
    }
    if(chunk.length)chunks.push(chunk);
    if(chunks.length===1){source+=leaf(name,items);manifest.push({key,name,count:items.length,pages:[]});continue;}
    let offset=0;
    const pages=chunks.map((items,index)=>{const page={name:`${name}Page${index}`,count:items.length,offset};offset+=items.length;source+=leaf(page.name,items);return page;});
    source+=`\ncontract ${name} is IArtBank {\n    error InvalidBankPage(uint256 page);\n`;
    pages.forEach((_,i)=>source+=`    address public immutable page${i};\n`);
    source+=`    constructor(address[${pages.length}] memory pages) {\n`;
    pages.forEach((page,i)=>source+=`        if (pages[${i}].code.length == 0 || IArtBank(pages[${i}]).count() != ${page.count}) revert InvalidBankPage(${i});\n        page${i} = pages[${i}];\n`);
    source+=`    }\n    function count() external pure returns (uint256) { return ${items.length}; }\n`;
    for(const [method,result,iface] of [['part','string','IArtBank'],['label','string','IArtBank'],['description','string','IArtBank'],['encodedPart','bytes','IArtBank']]){
      source+=`    function ${method}(uint8 index) external view returns (${result} memory) {\n`;
      pages.forEach((page,i)=>source+=`        if (index < ${page.offset+page.count}) return ${iface}(page${i}).${method}(index${page.offset?` - ${page.offset}`:''});\n`);
      source+='        revert InvalidTrait();\n    }\n';
    }
    source+='}\n';manifest.push({key,name,count:items.length,pages});
  }
  const names=['STEM_COUNT','CAP_COUNT','TEMPERAMENT_COUNT','GLASSES_COUNT','ACCESSORY_COUNT','HOBBY_COUNT'];
  const counts=layerKeys.map(k=>traits[k].length);
  const schema='// SPDX-License-Identifier: MIT\n// Generated by npm run build.\npragma solidity ^0.8.24;\nlibrary GenomeSchema {\n'+counts.map((n,i)=>`    uint256 internal constant ${names[i]} = ${n};\n`).join('')+`    uint256 internal constant MAX_SUPPLY = ${counts.reduce((a,b)=>a*b,1)};\n}\n`;
  return {source,manifest,schema};
}

export function generateSVGConstants({OPEN,GROUP,CLOSE,layerKeys,layerNames,renderLayerKeys,brushCapOffsets}) {
  for(const key of layerKeys)assertJSONSafeASCII(layerNames?.[key],`layerNames.${key}`);
  if(!Array.isArray(renderLayerKeys)||renderLayerKeys.length!==6||new Set(renderLayerKeys).size!==6||renderLayerKeys.some(key=>!layerKeys.includes(key)))throw new Error('Invalid render layer order');
  const accessoryLayer=layerKeys.indexOf('accessory'),capLayer=layerKeys.indexOf('cap');
  const brushRules=[brushCapOffsets?.chanterelle,brushCapOffsets?.sleepyHand];
  if(!Number.isInteger(brushCapOffsets?.accessory)||brushRules.some(rule=>!Number.isInteger(rule?.cap)||!Number.isInteger(rule?.x)||rule.x>=0))throw new Error('Invalid Paint It Green composition offsets');
  const header=OPEN+GROUP,chunkSize=20000,chunks=[];
  for(let offset=0;offset<header.length;offset+=chunkSize)chunks.push(header.slice(offset,offset+chunkSize));
  let source='// SPDX-License-Identifier: MIT\n// Generated by npm run build.\npragma solidity ^0.8.24;\n';
  chunks.forEach((chunk,i)=>{
    source+=`contract SVGHeaderPage${i} {\n    constructor() {\n        bytes memory data = bytes(${JSON.stringify(chunk)});\n        assembly (\"memory-safe\") { return(add(data, 32), mload(data)) }\n    }\n}\n`;
  });
  source+='contract SVGHeaderStore {\n';
  chunks.forEach((_,i)=>source+=`    address public immutable page${i};\n`);
  source+='    constructor() {\n';
  chunks.forEach((_,i)=>source+=`        page${i} = address(new SVGHeaderPage${i}());\n`);
  source+='    }\n    function page(uint256 i) external view returns (address source, uint256 length, uint256 offset) {\n';
  let offset=0;
  chunks.forEach((chunk,i)=>{
    source+=`        if (i == ${i}) return (page${i}, ${chunk.length}, ${offset});\n`;
    offset+=chunk.length;
  });
  source+='        revert();\n    }\n}\n';
  return source+`library SVGConstants {\n    uint256 internal constant HEADER_LENGTH = ${header.length};\n    uint256 internal constant HEADER_PAGES = ${chunks.length};\n    string internal constant CLOSE = ${JSON.stringify(CLOSE)};\n    function renderLayer(uint256 i) internal pure returns (uint256) {\n${renderLayerKeys.map((k,i)=>`        if (i == ${i}) return ${layerKeys.indexOf(k)};`).join('\n')}\n        revert();\n    }\n    function compositionOpen(uint48 genotype, uint256 layer) internal pure returns (string memory) {\n        if (layer != ${accessoryLayer} || uint8(genotype >> ${accessoryLayer*8}) != ${brushCapOffsets.accessory}) return "";\n        uint8 cap = uint8(genotype >> ${capLayer*8});\n${brushRules.map(rule=>`        if (cap == ${rule.cap}) return ${JSON.stringify(`<g transform="translate(${rule.x} 0)">`)};`).join('\n')}\n        return "";\n    }\n    function layerName(uint256 i) internal pure returns (string memory) {\n${layerKeys.map((k,i)=>`        if (i == ${i}) return ${JSON.stringify(layerNames[k])};`).join('\n')}\n        revert();\n    }\n}\n`;
}
